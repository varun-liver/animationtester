    char fileBuf[MAX_PATH] = { 0 };

    OPENFILENAMEA ofn{};
    ofn.lStructSize = sizeof(ofn);
    ofn.hwndOwner = glfwGetWin32Window(window);
    ofn.lpstrFilter = "Animation JSON (*.json)\0*.json\0All files (*.*)\0*.*\0";
    ofn.lpstrFile = fileBuf;
