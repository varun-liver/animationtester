// Free orbit camera for the left viewport: left-click-drag orbits,
// shift+left-click-drag pans, and scrolling (mouse wheel or a trackpad's
// two-finger swipe) zooms (dolly in/out) toward/away from a fixed pivot.
struct OrbitCamera {
    glm::vec3 target{ 0.0f, 1.0f, 0.0f }; // orbit pivot, roughly chest height
    float yaw = -60.0f;                   // degrees, around world up
    float pitch = 20.0f;                  // degrees, above the horizon
    float distance = 4.0f;
    static constexpr float kOrbitSensitivity = 0.3f;  // degrees per pixel
    static constexpr float kPanSensitivity = 0.0025f; // * distance, per pixel
    static constexpr float kZoomSensitivity = 0.4f;   // distance units per scroll tick
    static constexpr float kMinDistance = 0.5f;
    static constexpr float kMaxDistance = 30.0f;

    glm::vec3 forward() const {
        float ry = glm::radians(yaw), rp = glm::radians(pitch);
        return glm::normalize(glm::vec3(std::cos(rp) * std::cos(ry), std::sin(rp), std::cos(rp) * std::sin(ry)));
    }
    glm::vec3 eye() const { return target - forward() * distance; }
    glm::mat4 viewMatrix() const { return glm::lookAt(eye(), target, glm::vec3(0.0f, 1.0f, 0.0f)); }

    void orbit(double dx, double dy) {
        yaw += static_cast<float>(dx) * kOrbitSensitivity;
        pitch = std::clamp(pitch - static_cast<float>(dy) * kOrbitSensitivity, -89.0f, 89.0f);
    }
    void pan(double dx, double dy) {
        glm::vec3 fwd = forward();
        glm::vec3 right = glm::normalize(glm::cross(fwd, glm::vec3(0.0f, 1.0f, 0.0f)));
        glm::vec3 up = glm::cross(right, fwd);
        float scale = distance * kPanSensitivity;
        target += (-right * static_cast<float>(dx) + up * static_cast<float>(dy)) * scale;
    }
    void zoom(double scrollY) {
        distance = std::clamp(distance - static_cast<float>(scrollY) * kZoomSensitivity, kMinDistance, kMaxDistance);
    }
};

uint32_t findMemoryType(const VkPhysicalDeviceMemoryProperties& memProps, uint32_t typeBits, VkMemoryPropertyFlags want) {
    for (uint32_t i = 0; i < memProps.memoryTypeCount; ++i) {
        if ((typeBits & (1u << i)) && (memProps.memoryTypes[i].propertyFlags & want) == want) return i;
    }
    throw std::runtime_error("no suitable Vulkan memory type found");
}

// Native Windows "Open" file dialog, used by the menu bar's Open button.
// Returns the chosen path, or an empty string if the user cancelled.
