    // ---- recent files (plain text, one path per line, next to the exe) ----

    // A plausible Windows path: printable ASCII only (rejects anything
    // with embedded NULs or control bytes, which std::filesystem::path on
    // MinGW throws on when it tries to widen them - seen once already
    // from a corrupted recent_files.txt, so this file is treated as
    // untrusted on load rather than assumed well-formed).
    static bool looksLikePath(const std::string& s) {
        if (s.empty()) return false;
        for (unsigned char c : s) {
            if (c < 0x20 || c == 0x7f) return false;
        }
        return true;
    }

    void loadRecentFiles() {
        std::ifstream file(kRecentFilesPath);
        std::string line;
        while (std::getline(file, line)) {
            if (looksLikePath(line)) recentFiles_.push_back(line);
        }
    }

    void saveRecentFiles() {
        std::ofstream file(kRecentFilesPath, std::ios::trunc);
        for (const auto& path : recentFiles_) file << path << "\n";
    }

    // Moves `path` to the front of the recent list (adding it if new),
    // caps the list at kMaxRecentFiles, and persists it immediately.
    void addRecentFile(const std::string& path) {
        recentFiles_.erase(std::remove(recentFiles_.begin(), recentFiles_.end(), path), recentFiles_.end());
        recentFiles_.insert(recentFiles_.begin(), path);
        if (recentFiles_.size() > kMaxRecentFiles) recentFiles_.resize(kMaxRecentFiles);
        saveRecentFiles();
    }

    // Host-visible+coherent buffer, written once at load time. The rig is
    // tiny and static, so skipping a staging buffer keeps this simple.
    void createHostVisibleBuffer(const void* data, VkDeviceSize size, VkBufferUsageFlags usage, VkBuffer& buffer, VkDeviceMemory& memory) {
        VkBufferCreateInfo bufferInfo{ VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO };
        bufferInfo.size = size;
        bufferInfo.usage = usage;
        bufferInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
        VK_CHECK(disp_.createBuffer(&bufferInfo, nullptr, &buffer));

        VkMemoryRequirements memReq;
        disp_.getBufferMemoryRequirements(buffer, &memReq);

        VkMemoryAllocateInfo allocInfo{ VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO };
        allocInfo.allocationSize = memReq.size;
        allocInfo.memoryTypeIndex = findMemoryType(physicalDevice_.memory_properties, memReq.memoryTypeBits,
            VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
        VK_CHECK(disp_.allocateMemory(&allocInfo, nullptr, &memory));
        disp_.bindBufferMemory(buffer, memory, 0);

        void* mapped = nullptr;
        VK_CHECK(disp_.mapMemory(memory, 0, size, 0, &mapped));
        std::memcpy(mapped, data, static_cast<size_t>(size));
        disp_.unmapMemory(memory);
    }

    // ---- pipeline ----

    // Shaders are embedded directly in the executable (shaders_embedded.h,
    // generated by build_vk.sh from shaders/*.spv) rather than loaded from
    // disk at runtime, so the .exe has no sidecar files to ship with it.
    VkShaderModule loadShaderFromMemory(const unsigned char* code, size_t sizeBytes) {
        VkShaderModuleCreateInfo info{ VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO };
        info.codeSize = sizeBytes;
        info.pCode = reinterpret_cast<const uint32_t*>(code);
        VkShaderModule module;
        VK_CHECK(disp_.createShaderModule(&info, nullptr, &module));
        return module;
    }

    void createPipeline() {
        VkShaderModule vertModule = loadShaderFromMemory(character_vert_spv, character_vert_spv_len);
        VkShaderModule fragModule = loadShaderFromMemory(character_frag_spv, character_frag_spv_len);

        VkPipelineShaderStageCreateInfo vertStage{ VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO };
        vertStage.stage = VK_SHADER_STAGE_VERTEX_BIT;
        vertStage.module = vertModule;
        vertStage.pName = "main";

        VkPipelineShaderStageCreateInfo fragStage{ VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO };
        fragStage.stage = VK_SHADER_STAGE_FRAGMENT_BIT;
        fragStage.module = fragModule;
        fragStage.pName = "main";

        std::array<VkPipelineShaderStageCreateInfo, 2> stages{ vertStage, fragStage };

        VkVertexInputBindingDescription binding{};
        binding.binding = 0;
        binding.stride = sizeof(Vertex);
        binding.inputRate = VK_VERTEX_INPUT_RATE_VERTEX;

        std::array<VkVertexInputAttributeDescription, 3> attrs{};
        attrs[0] = { 0, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(Vertex, pos) };
        attrs[1] = { 1, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(Vertex, normal) };
        attrs[2] = { 2, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(Vertex, color) };

        VkPipelineVertexInputStateCreateInfo vertexInput{ VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO };
        vertexInput.vertexBindingDescriptionCount = 1;
        vertexInput.pVertexBindingDescriptions = &binding;
        vertexInput.vertexAttributeDescriptionCount = static_cast<uint32_t>(attrs.size());
        vertexInput.pVertexAttributeDescriptions = attrs.data();

        VkPipelineInputAssemblyStateCreateInfo inputAssembly{ VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO };
        inputAssembly.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

        VkPipelineViewportStateCreateInfo viewportState{ VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO };
        viewportState.viewportCount = 1;
        viewportState.scissorCount = 1;

        VkPipelineRasterizationStateCreateInfo rasterizer{ VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO };
        rasterizer.polygonMode = VK_POLYGON_MODE_FILL;
        rasterizer.lineWidth = 1.0f;
        rasterizer.cullMode = VK_CULL_MODE_NONE; // avoid any risk of a mis-wound cuboid face vanishing
        rasterizer.frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE;

        VkPipelineMultisampleStateCreateInfo multisampling{ VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO };
        multisampling.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;

        VkPipelineDepthStencilStateCreateInfo depthStencil{ VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO };
        depthStencil.depthTestEnable = VK_TRUE;
        depthStencil.depthWriteEnable = VK_TRUE;
        depthStencil.depthCompareOp = VK_COMPARE_OP_LESS;

        VkPipelineColorBlendAttachmentState colorBlendAttachment{};
        colorBlendAttachment.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT | VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
        colorBlendAttachment.blendEnable = VK_FALSE;

        VkPipelineColorBlendStateCreateInfo colorBlending{ VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO };
        colorBlending.attachmentCount = 1;
        colorBlending.pAttachments = &colorBlendAttachment;

        std::array<VkDynamicState, 2> dynamicStates{ VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR };
        VkPipelineDynamicStateCreateInfo dynamicState{ VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO };
        dynamicState.dynamicStateCount = static_cast<uint32_t>(dynamicStates.size());
        dynamicState.pDynamicStates = dynamicStates.data();

        VkPushConstantRange pushConstantRange{};
        pushConstantRange.stageFlags = VK_SHADER_STAGE_VERTEX_BIT;
        pushConstantRange.offset = 0;
        pushConstantRange.size = sizeof(PushConstants);

        VkPipelineLayoutCreateInfo layoutInfo{ VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
        layoutInfo.pushConstantRangeCount = 1;
        layoutInfo.pPushConstantRanges = &pushConstantRange;
        VK_CHECK(disp_.createPipelineLayout(&layoutInfo, nullptr, &pipelineLayout_));

        VkPipelineRenderingCreateInfo renderingInfo{ VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO };
        renderingInfo.colorAttachmentCount = 1;
        renderingInfo.pColorAttachmentFormats = &swapchain_.image_format;
        renderingInfo.depthAttachmentFormat = depthFormat_;

        VkGraphicsPipelineCreateInfo pipelineInfo{ VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO };
        pipelineInfo.pNext = &renderingInfo;
        pipelineInfo.stageCount = static_cast<uint32_t>(stages.size());
        pipelineInfo.pStages = stages.data();
        pipelineInfo.pVertexInputState = &vertexInput;
        pipelineInfo.pInputAssemblyState = &inputAssembly;
        pipelineInfo.pViewportState = &viewportState;
        pipelineInfo.pRasterizationState = &rasterizer;
        pipelineInfo.pMultisampleState = &multisampling;
        pipelineInfo.pDepthStencilState = &depthStencil;
        pipelineInfo.pColorBlendState = &colorBlending;
        pipelineInfo.pDynamicState = &dynamicState;
        pipelineInfo.layout = pipelineLayout_;
        pipelineInfo.renderPass = VK_NULL_HANDLE;

        VK_CHECK(disp_.createGraphicsPipelines(VK_NULL_HANDLE, 1, &pipelineInfo, nullptr, &pipeline_));

        disp_.destroyShaderModule(vertModule, nullptr);
        disp_.destroyShaderModule(fragModule, nullptr);
    }

    // imageAvailable/fences are per-frame-in-flight (indexed by currentFrame_).
    // renderFinished must instead be per-swapchain-image (indexed by the
    // acquired imageIndex): with MAILBOX present mode, images can be
    // acquired out of the simple round-robin order frames are submitted in,
    // so a frame-indexed signal semaphore can still be "in flight" at a
    // swapchain's present operation when it's reused (VUID-vkQueueSubmit-
    // pSignalSemaphores-00067). See createRenderFinishedSemaphores().
    void createSyncObjects() {
        imageAvailableSemaphores_.resize(kMaxFramesInFlight);
        inFlightFences_.resize(kMaxFramesInFlight);

        VkSemaphoreCreateInfo semInfo{ VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO };
        VkFenceCreateInfo fenceInfo{ VK_STRUCTURE_TYPE_FENCE_CREATE_INFO };
        fenceInfo.flags = VK_FENCE_CREATE_SIGNALED_BIT;

        for (int i = 0; i < kMaxFramesInFlight; ++i) {
            VK_CHECK(disp_.createSemaphore(&semInfo, nullptr, &imageAvailableSemaphores_[i]));
            VK_CHECK(disp_.createFence(&fenceInfo, nullptr, &inFlightFences_[i]));
        }

        createRenderFinishedSemaphores();
    }

    void createRenderFinishedSemaphores() {
        renderFinishedSemaphores_.resize(swapchainImages_.size());
        VkSemaphoreCreateInfo semInfo{ VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO };
        for (auto& sem : renderFinishedSemaphores_) {
            VK_CHECK(disp_.createSemaphore(&semInfo, nullptr, &sem));
        }
    }

    void destroyRenderFinishedSemaphores() {
        for (auto sem : renderFinishedSemaphores_) disp_.destroySemaphore(sem, nullptr);
        renderFinishedSemaphores_.clear();
    }

