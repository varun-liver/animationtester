#!/usr/bin/env bash
# Builds the Vulkan Minecraft-character rig viewer (character_viewer.cpp)
# and its SPIR-V shaders.
#
# Requires:
#   - The LunarG Vulkan SDK installed (sets $VULKAN_SDK, or installed under
#     C:/VulkanSDK/<version>/).
#   - deps/glfw, deps/glm, deps/VkBootstrap.{h,cpp}, deps/VkBootstrapDispatch.h,
#     deps/volk.{h,c}, deps/imgui/ (already copied into this directory).
set -euo pipefail
cd "$(dirname "$0")"

# Locate the Vulkan SDK (env var first, else newest C:/VulkanSDK/<ver>).
SDK="${VULKAN_SDK:-}"
if [ -z "$SDK" ]; then
    SDK=$(ls -d /c/VulkanSDK/*/ 2>/dev/null | sort -V | tail -1)
fi
if [ -z "$SDK" ] || [ ! -d "$SDK" ]; then
    echo "error: Vulkan SDK not found. Install it, or set VULKAN_SDK." >&2
    exit 1
fi
SDK="${SDK%/}"
echo "Using Vulkan SDK: $SDK"

GLSLC="$SDK/Bin/glslc.exe"
if [ ! -f "$GLSLC" ]; then
    echo "error: glslc not found at $GLSLC" >&2
    exit 1
fi

echo "Compiling shaders..."
"$GLSLC" shaders/character.vert -o shaders/character.vert.spv
"$GLSLC" shaders/character.frag -o shaders/character.frag.spv

echo "Embedding shaders into shaders_embedded.h..."
# xxd -i takes at most one input file (a 2nd argument is an OUTPUT file,
# not a 2nd input) - call it once per shader, not with both at once.
{
    echo "// Auto-generated by build_vk.sh from shaders/*.spv - do not edit."
    echo "#pragma once"
    (cd shaders && xxd -i character.vert.spv)
    (cd shaders && xxd -i character.frag.spv)
} > shaders_embedded.h

INCLUDES=(-Ideps -Ideps/glfw/include -Ideps/glm -Ideps/imgui -Ideps/imgui/backends -I"$SDK/Include")
DEFINES=(-DVK_NO_PROTOTYPES)
CXXFLAGS=(-O2 -std=c++17 "${INCLUDES[@]}" "${DEFINES[@]}")

# {source file -> object file}, compiled only if missing/out of date.
SOURCES=(
    "deps/VkBootstrap.cpp:deps/VkBootstrap.o"
    "deps/imgui/imgui.cpp:deps/imgui/imgui.o"
    "deps/imgui/imgui_draw.cpp:deps/imgui/imgui_draw.o"
    "deps/imgui/imgui_tables.cpp:deps/imgui/imgui_tables.o"
    "deps/imgui/imgui_widgets.cpp:deps/imgui/imgui_widgets.o"
    "deps/imgui/backends/imgui_impl_glfw.cpp:deps/imgui/backends/imgui_impl_glfw.o"
    "deps/imgui/backends/imgui_impl_vulkan.cpp:deps/imgui/backends/imgui_impl_vulkan.o"
    "character_viewer.cpp:character_viewer.o"
)

OBJECTS=()
for entry in "${SOURCES[@]}"; do
    src="${entry%%:*}"
    obj="${entry##*:}"
    OBJECTS+=("$obj")
    # character_viewer.cpp also depends on the freshly (re)generated embedded-shader header.
    extraDep=""
    [ "$src" = "character_viewer.cpp" ] && extraDep="shaders_embedded.h"
    if [ ! -f "$obj" ] || [ "$src" -nt "$obj" ] || { [ -n "$extraDep" ] && [ "$extraDep" -nt "$obj" ]; }; then
        echo "Compiling $src..."
        g++ "${CXXFLAGS[@]}" -c "$src" -o "$obj"
    fi
done

echo "Linking..."
g++ -static -static-libgcc -static-libstdc++ -mwindows \
    "${OBJECTS[@]}" \
    deps/glfw/lib-mingw-w64/libglfw3.a \
    -lgdi32 -lcomdlg32 -o character_viewer.exe

echo "Built character_viewer.exe"
